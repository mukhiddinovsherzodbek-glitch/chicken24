    async def orders_with_items(
        self, start: datetime | None = None, end: datetime | None = None
    ) -> list[tuple[dict, list[dict]]]:
        """[start, end) oralig'idagi BARCHA buyurtmalar (bekor qilinganlari ham), qatorlari bilan.
        start/end None bo'lsa - chegara yo'q."""
        d = self._db
        where, params = [], []
        if start is not None:
            where.append(f"{d.ts('o.created_at')} >= {d.ts_param()}")
            params.append(start.isoformat())
        if end is not None:
            where.append(f"{d.ts('o.created_at')} < {d.ts_param()}")
            params.append(end.isoformat())
        sql = "SELECT o.* FROM orders o" + (" WHERE " + " AND ".join(where) if where else "") + " ORDER BY o.id"
        orders = await d.fetch_dicts(sql, params)
        if not orders:
            return []
        ids = [o["id"] for o in orders]
        items: dict[int, list[dict]] = {i: [] for i in ids}
        # Bo'laklab (parametrlar soni chegarasidan oshmaslik uchun)
        for chunk_start in range(0, len(ids), 500):
            chunk = ids[chunk_start:chunk_start + 500]
            rows = await d.fetch_dicts(
                "SELECT order_id, item_id, name, price, qty, line_total FROM order_items "
                f"WHERE order_id IN ({','.join('?' * len(chunk))}) ORDER BY order_id, id",
                chunk,
            )
            for row in rows:
                items[row["order_id"]].append(row)
        return [(o, items[o["id"]]) for o in orders]

