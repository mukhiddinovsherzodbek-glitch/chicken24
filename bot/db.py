class _SqliteBackend:
    """aiosqlite: bitta ulanish, har yozuvdan keyin commit (avvalgi xatti-harakat)."""

    kind = SQLITE

    def __init__(self, conn: aiosqlite.Connection) -> None:
        self.conn = conn

    # SQL bo'laklari (dialekt)
    @staticmethod
    def ts(expr: str) -> str:
        return f"julianday({expr})"

    @staticmethod
    def ts_param() -> str:
        return "julianday(?)"

    @staticmethod
    def age_seconds(later_param_col: str) -> str:
        """(? vaqt) - (ustun vaqti), soniyalarda; ? - parametr."""
        return f"(julianday(?) - julianday({later_param_col})) * 86400.0"

    @staticmethod
    def num_param() -> str:
        return "?"

    async def execute(self, sql: str, params: Sequence = (), *, retry: bool = True) -> int:
        cursor = await self.conn.execute(sql, params)
        await self.conn.commit()
        return cursor.rowcount

    async def fetchone(self, sql: str, params: Sequence = ()) -> tuple | None:
        cursor = await self.conn.execute(sql, params)
        row = await cursor.fetchone()
        return tuple(row) if row is not None else None

    async def fetchall(self, sql: str, params: Sequence = ()) -> list[tuple]:
        cursor = await self.conn.execute(sql, params)
        return [tuple(r) for r in await cursor.fetchall()]

    async def fetch_dicts(self, sql: str, params: Sequence = ()) -> list[dict]:
        cursor = await self.conn.execute(sql, params)
        columns = [c[0] for c in cursor.description]
        return [dict(zip(columns, row)) for row in await cursor.fetchall()]

    async def insert_with_children(self, parent_sql: str, parent_params: Sequence,
                                   child_sql: str, child_rows: list[tuple]) -> int:
        """Ota qator + bola qatorlar bitta tranzaksiyada; bola qatorlar boshiga ota ID qo'shiladi."""
        try:
            cursor = await self.conn.execute(parent_sql, parent_params)
            parent_id = int(cursor.lastrowid)
            await self.conn.executemany(child_sql, [(parent_id, *row) for row in child_rows])
            await self.conn.commit()
        except Exception:
            await self.conn.rollback()
            raise
        return parent_id


_PLACEHOLDER = re.compile(r"\?")


def to_pg_sql(sql: str) -> str:
    """'... = ? AND ... = ?' -> '... = $1 AND ... = $2' (SQL matnlarimizda ? faqat parametr belgisi)."""
    counter = iter(range(1, 10_000))
    return _PLACEHOLDER.sub(lambda _m: f"${next(counter)}", sql)


def clean_pg_error(exc: BaseException) -> DatabaseError:
    """Postgres xatosi -> DatabaseError: faqat xato turi, SQLSTATE va xabarning birinchi qatori.
    DETAIL qismi (unda qator qiymatlari - telefon, ism bo'lishi mumkin) tashlab yuboriladi."""
    message = str(exc.args[0]) if exc.args else ""
    sqlstate = getattr(exc, "sqlstate", None)
    text = type(exc).__name__ + (f" [{sqlstate}]" if sqlstate else "")
    if message:
        text += ": " + message.splitlines()[0][:300]
    return DatabaseError(scrub(text))


def _rowcount(status: str) -> int:
    """asyncpg holat satri: 'UPDATE 1' / 'INSERT 0 1' / 'DELETE 3' -> oxirgi son."""
    try:
        return int(status.rsplit(" ", 1)[-1])
    except (ValueError, AttributeError):
        return 0


class _PostgresBackend:
    """asyncpg pool. Ulanish uzilsa (Neon uxlab qolgan, tarmoq) xavfsiz so'rovlar bir marta qayta uriniladi."""

    kind = POSTGRES

    def __init__(self, pool: Any) -> None:
        import asyncpg

        self.pool = pool
        self._asyncpg = asyncpg
        self._retryable = (
            asyncpg.exceptions.ConnectionDoesNotExistError,
            asyncpg.exceptions.CannotConnectNowError,
            ConnectionError,
            OSError,
            asyncio.TimeoutError,
        )

    @staticmethod
    def ts(expr: str) -> str:
        return f"({expr})::timestamptz"

    @staticmethod
    def ts_param() -> str:
        return "(?::text)::timestamptz"

    @staticmethod
    def age_seconds(later_param_col: str) -> str:
        return f"EXTRACT(EPOCH FROM ((?::text)::timestamptz - ({later_param_col})::timestamptz))"

    @staticmethod
    def num_param() -> str:
        return "(?::float8)"

    @staticmethod
    def clean_error(exc: BaseException) -> DatabaseError:
        return clean_pg_error(exc)

    async def _run(self, method: str, sql: str, params: Sequence, retry: bool) -> Any:
        sql = to_pg_sql(sql)
        for attempt in (1, 2):
            try:
                async with self.pool.acquire() as con:
                    return await getattr(con, method)(sql, *params)
            except self._retryable as exc:
                if not retry or attempt == 2:
                    raise self.clean_error(exc) from None
                logger.warning("Postgres ulanishi uzildi (%s) - qayta urinilmoqda", type(exc).__name__)
                await asyncio.sleep(0.5)
            except self._asyncpg.PostgresError as exc:
                raise self.clean_error(exc) from None
        raise AssertionError("unreachable")  # pragma: no cover

    async def execute(self, sql: str, params: Sequence = (), *, retry: bool = True) -> int:
        return _rowcount(await self._run("execute", sql, params, retry))

    async def fetchone(self, sql: str, params: Sequence = ()) -> tuple | None:
        row = await self._run("fetchrow", sql, params, True)
        return tuple(row.values()) if row is not None else None

    async def fetchall(self, sql: str, params: Sequence = ()) -> list[tuple]:
        return [tuple(r.values()) for r in await self._run("fetch", sql, params, True)]

    async def fetch_dicts(self, sql: str, params: Sequence = ()) -> list[dict]:
        return [dict(r.items()) for r in await self._run("fetch", sql, params, True)]

    async def insert_with_children(self, parent_sql: str, parent_params: Sequence,
                                   child_sql: str, child_rows: list[tuple]) -> int:
        # Qayta urinilmaydi: buyurtma ikki marta yozilmasligi uchun (xato bo'lsa handler mijozga aytadi)
        try:
            async with self.pool.acquire() as con:
                async with con.transaction():
                    parent_id = int(await con.fetchval(to_pg_sql(parent_sql + " RETURNING id"), *parent_params))
                    await con.executemany(to_pg_sql(child_sql), [(parent_id, *row) for row in child_rows])
        except (self._asyncpg.PostgresError, *self._retryable) as exc:
            raise self.clean_error(exc) from None
        return parent_id


