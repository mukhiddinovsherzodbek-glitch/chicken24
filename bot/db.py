    async def cancel_order(self, order_id: int, user_id: int, now: datetime, window_seconds: float) -> str:
        """Mijoz o'z buyurtmasini bekor qiladi (faqat `window_seconds` ichida). Atomar: bitta UPDATE."""
        d = self._db
        changed = await d.execute(
            f"""
            UPDATE orders SET status = 'cancelled', cancelled_at = ?
            WHERE id = ? AND user_id = ? AND status != 'cancelled'
              AND {d.age_seconds('created_at')} <= {d.num_param()}
            """,
            (now.isoformat(), order_id, user_id, now.isoformat(), float(window_seconds)),
            retry=False,
        )
        if changed:
            return CANCEL_OK
        order = await self.get_order(order_id)
        if order is None or order["user_id"] != user_id:
            return CANCEL_NOT_FOUND
        if order["status"] == "cancelled":
            return CANCEL_ALREADY
        return CANCEL_EXPIRED

