class Database:
    """Bitta interfeys: Database(path) - SQLite; Database(dsn="postgresql://...") - PostgreSQL."""

    def __init__(self, path: Path | str | None = None, *, dsn: str | None = None,
                 server_settings: dict[str, str] | None = None) -> None:
        if dsn and not is_postgres_url(dsn):
            raise ValueError("DATABASE_URL postgres:// yoki postgresql:// bilan boshlanishi kerak")
        if not dsn and path is None:
            raise ValueError("SQLite fayl yo'li yoki Postgres DATABASE_URL kerak")
        self._path = Path(path) if path is not None else None
        self._dsn = dsn or None
        self._server_settings = dict(server_settings or {})
        self._conn: aiosqlite.Connection | None = None
        self._pool: Any = None
        self._b: _SqliteBackend | _PostgresBackend | None = None
        # Qayta yuborish bir vaqtda faqat bitta ishlashi uchun (connect() da, joriy event loop'da yaratiladi)
        self.resend_lock: asyncio.Lock | None = None
        # Admin'ga yetmagan buyurtma bo'lishi mumkin bo'lgan eng so'nggi payt (None - hammasi tekshirilgan).
        # Fon qayta yuborish bazaga faqat shunda murojaat qiladi: bo'sh bazaga har 2 daqiqada so'rov
        # yuborilmaydi (Neon bepul rejasi uxlay oladi va oylik hisoblash soatlari tejaladi).
        self._unnotified_since: datetime | None = None

    @classmethod
    def from_config(cls, config: Any) -> "Database":
        return cls(config.db_path, dsn=getattr(config, "database_url", None))

    # ------------------------------------------------------------ ulanish

    @property
    def kind(self) -> str:
        return POSTGRES if self._dsn else SQLITE

    @property
    def path(self) -> Path | None:
        return self._path

    def describe(self) -> str:
        return f"PostgreSQL ({describe_dsn(self._dsn)})" if self._dsn else f"SQLite ({self._path})"

    async def connect(self) -> None:
        self.resend_lock = asyncio.Lock()
        self._unnotified_since = datetime.now(timezone.utc)  # ishga tushganda - noma'lum, tekshiriladi
        if self._dsn:
            await self._connect_postgres()
        else:
            await self._connect_sqlite()
        logger.info("Baza ulandi: %s", self.describe())

    async def _connect_sqlite(self) -> None:
        assert self._path is not None
        self._path.parent.mkdir(parents=True, exist_ok=True)
        self._conn = await aiosqlite.connect(self._path)
        await self._conn.execute("PRAGMA foreign_keys = ON")
        await self._conn.execute("PRAGMA journal_mode = WAL")
        await self._conn.executescript(SCHEMA)
        self._b = _SqliteBackend(self._conn)
        await self._migrate_sqlite()
        await self._conn.commit()

    async def _connect_postgres(self) -> None:
        import asyncpg

        dsn, ssl = pg_connect_params(self._dsn)
        # Vaqtlar har doim "+00:00" qo'shimchali matn - sessiya vaqt zonasi natijaga ta'sir qilmaydi
        extra, search_path = split_server_settings(self._server_settings)
        settings = {"application_name": "chicken24-bot", **extra}

        async def setup(con: Any) -> None:
            # Har acquire'da: pool ulanishni qaytarganda RESET ALL qiladi va SET qilingan search_path yo'qoladi
            await apply_search_path(con, search_path)

        try:
            self._pool = await asyncpg.create_pool(
                dsn,
                ssl=ssl,
                min_size=0,                            # bo'sh turganda ochiq ulanish qolmaydi (Neon uxlay oladi)
                max_size=5,
                max_inactive_connection_lifetime=60,   # 1 daqiqa ishlatilmagan ulanish yopiladi
                statement_cache_size=0,                # Neon pooler (PgBouncer) bilan ham ishlashi uchun
                command_timeout=30,
                timeout=30,
                server_settings=settings,
                setup=setup if search_path else None,  # ishchi bot: None (search_path bermaydi)
            )
            async with self._pool.acquire() as con:
                async with con.transaction():
                    # Bir vaqtda ikki nusxa (deploy payti) jadval yaratishda to'qnashmasin
                    await con.execute("SELECT pg_advisory_xact_lock(724824001)")
                    await con.execute(PG_SCHEMA)
                    for table, columns in PG_MIGRATIONS.items():
                        for column, ctype in columns.items():
                            # Nomlar faqat yuqoridagi doimiy lug'atdan - foydalanuvchi ma'lumoti emas
                            await con.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {ctype}")
                    await con.execute(
                        "UPDATE orders SET items_total = total, delivery_fee = 0 WHERE items_total IS NULL"
                    )
                    await con.execute(POST_MIGRATION_SQL)
                    if await con.fetchval(DUPLICATE_REFS_SQL):
                        logger.warning(DUPLICATE_REFS_WARNING)
                    else:
                        await con.execute(UNIQUE_REF_SQL)
                    if await enable_rls(con):
                        logger.info("Row Level Security yoqildi (barcha jadvallar)")
        except Exception as exc:
            if self._pool is not None:
                await self._pool.close()
                self._pool = None
            if isinstance(exc, asyncpg.PostgresError):
                raise clean_pg_error(exc) from None
            raise
        self._b = _PostgresBackend(self._pool)

    async def _migrate_sqlite(self) -> None:
        """Eski bazada yetishmayotgan ustunlarni qo'shadi (ALTER TABLE ... ADD COLUMN)."""
        for table, columns in MIGRATIONS.items():
            cursor = await self.conn.execute(f"PRAGMA table_info({table})")
            existing = {row[1] for row in await cursor.fetchall()}
            for column, ctype in columns.items():
                if column not in existing:
                    # Nomlar faqat yuqoridagi doimiy lug'atdan - foydalanuvchi ma'lumoti emas
                    await self.conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {ctype}")
                    logger.info("Baza yangilandi: %s.%s qo'shildi", table, column)
        # Yetkazish narxidan oldingi buyurtmalar: total = faqat taomlar, yetkazish 0 edi
        cursor = await self.conn.execute(
            "UPDATE orders SET items_total = total, delivery_fee = 0 WHERE items_total IS NULL"
        )
        if cursor.rowcount:
            logger.info("Eski %d ta buyurtmaga items_total/delivery_fee to'ldirildi", cursor.rowcount)
        await self.conn.execute(POST_MIGRATION_SQL)
        cursor = await self.conn.execute(DUPLICATE_REFS_SQL)
        if await cursor.fetchone():
            logger.warning(DUPLICATE_REFS_WARNING)
        else:
            await self.conn.execute(UNIQUE_REF_SQL)

    async def close(self) -> None:
        if self._conn is not None:
            await self._conn.close()
            self._conn = None
        if self._pool is not None:
            await self._pool.close()
            self._pool = None
        self._b = None

    @property
    def conn(self) -> aiosqlite.Connection:
        """SQLite ulanishi (faqat SQLite rejimida; testlar uchun)."""
        if self._dsn:
            raise RuntimeError("conn faqat SQLite rejimida mavjud")
        if self._conn is None:
            raise RuntimeError("Baza ulanmagan: avval connect() chaqiring")
        return self._conn

    @property
    def _db(self) -> _SqliteBackend | _PostgresBackend:
        if self._b is None:
            raise RuntimeError("Baza ulanmagan: avval connect() chaqiring")
        return self._b

    @asynccontextmanager
    async def pg_connection(self) -> AsyncIterator[Any]:
        """Postgres ulanishi (ko'chirish skripti va testlar uchun)."""
        if self._pool is None:
            raise RuntimeError("Postgres ulanmagan")
        async with self._pool.acquire() as con:
            yield con

